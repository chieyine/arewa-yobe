import {chromium} from 'playwright';
const browser=await chromium.launch();
const page=await browser.newPage({viewport:{width:1440,height:1000}});
await page.goto('http://localhost:3107');
await page.getByRole('heading',{name:'Sign in',exact:true}).waitFor();
await page.waitForTimeout(4900);
await page.mouse.move(1300,500);await page.mouse.move(500,500);
const before=await page.locator('.terrain-svg').evaluate(el=>getComputedStyle(el).transform);
await page.waitForTimeout(650);
const after=await page.locator('.terrain-svg').evaluate(el=>getComputedStyle(el).transform);
if(before===after)throw Error('Sculpture is not moving');
if(await page.locator('.contour-glints path').count()!==3)throw Error('Contour highlights missing');
await page.emulateMedia({reducedMotion:'reduce'});
await page.waitForFunction(()=>!document.querySelector('.terrain-svg').getAnimations({subtree:true}).some(a=>a.playState==='running'),{},{timeout:2000});
const active=await page.locator('.terrain-svg').evaluate(el=>el.getAnimations({subtree:true}).filter(a=>a.playState==='running').length);
if(active)throw Error('Reduced-motion preference left artwork moving');
await page.setViewportSize({width:360,height:800});
if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth))throw Error('Mobile overflow');
console.log('PASS: measured sculpture movement, three contour highlights, interaction replay, reduced-motion cancellation and mobile width.');
await browser.close();
